import { chromium } from "playwright";
import fs from "node:fs";
const port = process.argv[3] ?? "8097";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1380, height: 900 } });
const base = `http://localhost:${port}/index.html`;
const out = process.argv[2] ?? "/tmp/claude-0/-home-claude/d2433efc-dba1-5080-a930-43a82e41e69f/scratchpad/shots";
fs.mkdirSync(out, { recursive: true });
const shot = (name) => page.screenshot({ path: `${out}/${name}-${port}.png`, fullPage: true });
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message));
await page.goto(`${base}#/payroll`);
await page.waitForTimeout(900);
await shot("payroll");
await page.getByRole("row", { name: /Vanessa J/ }).first().click();
await page.waitForTimeout(600);
await shot("payroll-sheet");
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
await page.getByRole("tab", { name: "Week grid" }).click();
await page.waitForTimeout(500);
await shot("payroll-grid");
await page.getByRole("button", { name: "Preview export file" }).click();
await page.waitForTimeout(500);
await shot("payroll-export");
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Close export preview" }).click().catch(() => {});
await page.waitForTimeout(300);
await page.getByRole("tab", { name: "Employee roster" }).click();
await page.getByRole("tab", { name: /Needs review/ }).click();
await page.waitForTimeout(500);
await shot("payroll-review");
await browser.close();
